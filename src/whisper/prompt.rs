//! The punctuation prompt: a short punctuated sentence in the speech's language, given to the
//! decoder as the previous text (`<|startofprev|>`, as transcribe.cpp's `--initial-prompt`). On
//! long readings Whisper large-v3-turbo often drops into lowercase without punctuation; with
//! punctuated text before the window it mostly keeps casing and punctuation. The idea and the
//! choice of languages follow the VoiceInk dictation app.

use super::tokenizer::Tokenizer;

/// The ids of the sentence of the language `code`, where they spell it in `tok`'s vocabulary (all
/// multilingual models share their text tokens); empty for a language without one.
pub fn ids(code: &str, tok: &Tokenizer) -> Vec<usize> {
  let Some(&(_, text, ids)) = PROMPTS.iter().find(|p| p.0 == code) else { return Vec::new() };
  let ids: Vec<usize> = ids.iter().map(|&i| i as usize).collect();
  let spelled = ids.iter().all(|&i| i < tok.len())
    && ids.iter().flat_map(|&i| tok.bytes(i)).copied().eq(format!(" {text}").bytes());
  if spelled { ids } else { Vec::new() }
}

